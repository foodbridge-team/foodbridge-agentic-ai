  const originalText = new WeakMap();
  const translatedText = new WeakMap();
  const attributeNames = ["placeholder", "title", "aria-label", "alt"];
  const reverseTranslations = new Map(Object.entries(translations).map(([english, kannada]) => [kannada, english]));
  let currentLanguage = localStorage.getItem("foodbridge_language") === "kn" ? "kn" : "en";
  let observer;

  function translateValue(value, language) {
    const trimmed = value.trim();
    if (!trimmed) return value;
    const leadingWhitespace = value.slice(0, value.length - value.trimStart().length);
    const trailingWhitespace = value.slice(value.trimEnd().length);
    const preserveWhitespace = (text) => `${leadingWhitespace}${text}${trailingWhitespace}`;

    let english = reverseTranslations.get(trimmed) || trimmed;
    if (!originalText.has(value)) {
      const translatedValue = reverseTranslations.get(value);
      if (translatedValue) english = translatedValue;
    }
    if (language === "en") return preserveWhitespace(english);

    const translated = translations[english];
    if (translated) return preserveWhitespace(translated);
    const accuracyMatch = english.match(/^Device location confirmed \(±(.+) m\)\. Tracking while this form is open\.$/);
    if (accuracyMatch && language === "kn") {
      return preserveWhitespace(`ಸಾಧನದ ಸ್ಥಳ ದೃಢವಾಗಿದೆ (±${accuracyMatch[1]} ಮೀ). ಈ ಫಾರ್ಮ್ ತೆರೆದಿರುವಾಗ ಟ್ರ್ಯಾಕ್ ಆಗುತ್ತದೆ.`);
    }
    if (language === "kn") {
      const translatedText = Object.entries(translations)
        .filter(([source]) => source.length >= 5 && english.includes(source))
        .sort(([left], [right]) => right.length - left.length)
        .reduce((result, [source, target]) => {
          const escaped = source.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
          const prefix = /^[\p{L}\p{N}]/u.test(source) ? "(^|[^\\p{L}\\p{N}])" : "";
          const suffix = /[\p{L}\p{N}]$/u.test(source) ? "(?=$|[^\\p{L}\\p{N}])" : "";
          const pattern = new RegExp(`${prefix}${escaped}${suffix}`, "giu");
          return result.replace(pattern, (match, boundary) => `${boundary || ""}${target}`);
        }, english);
      return preserveWhitespace(translatedText);
    }
    return preserveWhitespace(english);
  }

  function translateTextNode(node) {
    const current = node.nodeValue || "";
    const priorTranslation = translatedText.get(node);
    let english = originalText.get(node);
    if (priorTranslation !== undefined && current !== priorTranslation) {
      english = current;
      originalText.set(node, english);
    } else if (english === undefined) {
      english = reverseTranslations.get(current.trim()) || current;
      originalText.set(node, english);
    }

    const next = translateValue(english, currentLanguage);
    if (next !== current) {
      translatedText.set(node, next);
      node.nodeValue = next;
    } else {
      translatedText.set(node, current);
    }
  }

  function localize(root = document.documentElement) {
    if (!root) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) translateTextNode(node);

    const elements = root.nodeType === Node.ELEMENT_NODE ? [root, ...root.querySelectorAll("*")] : [...root.querySelectorAll("*")];
    elements.forEach((element) => {
      attributeNames.forEach((attribute) => {
        if (!element.hasAttribute(attribute)) return;
        const sourceKey = `data-i18n-${attribute}`;
        const original = element.getAttribute(sourceKey) ?? element.getAttribute(attribute);
        if (!element.hasAttribute(sourceKey)) element.setAttribute(sourceKey, original);
        element.setAttribute(attribute, translateValue(original, currentLanguage));
      });
    });
  }

  function setLanguage(language, notify = false) {
    currentLanguage = language === "kn" ? "kn" : "en";
    localStorage.setItem("foodbridge_language", currentLanguage);
    document.documentElement.lang = currentLanguage === "kn" ? "kn" : "en";
    localize();
    document.title = translateValue(document.title, currentLanguage);
    document.querySelectorAll("[data-language-toggle]").forEach((button) => {
      const label = button.querySelector("[data-language-label]") || button;
      label.textContent = currentLanguage === "en" ? "ಕನ್ನಡ" : "English";
      button.setAttribute("aria-label", currentLanguage === "en" ? "Switch language to Kannada" : "ಭಾಷೆಯನ್ನು ಇಂಗ್ಲಿಷ್‌ಗೆ ಬದಲಾಯಿಸಿ");
      button.setAttribute("title", currentLanguage === "en" ? "Switch language to Kannada" : "ಭಾಷೆಯನ್ನು ಇಂಗ್ಲಿಷ್‌ಗೆ ಬದಲಾಯಿಸಿ");
    });
    if (notify && typeof window.showToast === "function") {
      window.showToast(
        currentLanguage === "kn" ? "ಭಾಷೆಯನ್ನು ಕನ್ನಡಕ್ಕೆ ಬದಲಾಯಿಸಲಾಗಿದೆ" : "Language switched to English",
        "info"
      );
    }
  }

  window.foodBridgeTranslate = (text) => translateValue(String(text), currentLanguage);
